# This script is the source of all replication CSV files used by the
# table and figure scripts. It runs the fuzzy location-based specification for
# the main outcome and the covariate-balance outcome, then writes summary()
# tables with confidence bands, WBATE, and LBATE rows included.

get_script_dir <- function() {
  file_arg <- grep("^--file=", commandArgs(trailingOnly = FALSE), value = TRUE)
  if (length(file_arg) > 0) {
    return(normalizePath(dirname(sub("^--file=", "", file_arg[1])), winslash = "/"))
  }
  normalizePath(getwd(), winslash = "/")
}

